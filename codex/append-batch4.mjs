function cn(n) {
  const d = '零一二三四五六七八九'; let s = '';
  if (n >= 1000) { s += d[Math.floor(n / 1000)] + '千'; n %= 1000; if (n > 0 && n < 100) s += '零'; }
  if (n >= 100) { s += d[Math.floor(n / 100)] + '百'; n %= 100; if (n > 0 && n < 10) s += '零'; }
  if (n >= 10) { const t = Math.floor(n / 10); s += (t > 1 ? d[t] : '') + '十'; n %= 10; }
  if (n > 0) s += d[n];
  return s;
}
